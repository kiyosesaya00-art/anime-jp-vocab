# 太短/太常见 → 易误报，检索时跳过（这些即使真出现也很可能是普通用法）
STOP = {"以来","以上","上で","次第","とは","なり","ぬ","げ","限り","ものだ","ことだ",
        "ながら","つつ","なんて","とか","すら","ところだ","上","末","にて"}

def variants(form):
    form = form.replace("〜","").replace("　","").replace("(", "").replace(")","")
    parts = re.split(r"[・/]", form)
    out = []
    for p in parts:
        p = p.strip()
        # 去掉形如 A〜B 里剩下的占位（已无〜），保留纯假名/汉字串
        if not p:
            continue
        out.append(p)
    return out

def build(index, level):
    for form in index:
        for v in variants(form):
            if len(v) < 3:      # 太短跳过
                continue
            if v in STOP:
                continue
            yield (v, form, level)

TOKENS = list(build(N2, "N2")) + list(build(N1, "N1"))

segs = json.load(open("asr_full.json", encoding="utf-8"))

def mmss(t): return f"{int(t)//60:02d}:{int(t)%60:02d}"

seen = {}   # form -> hit
for s in segs:
    txt = s["text"]
    for v, form, level in TOKENS:
        if v in txt:
            key = (level, form)
            if key in seen:
                continue
            seen[key] = {"level":level,"form":form,"token":v,
                         "time":round(s["start"],2),"mmss":mmss(s["start"]),
                         "sentence":txt.strip()}

hits = sorted(seen.values(), key=lambda x:(x["level"]!="N2", x["time"]))
for h in hits:
    print(f'[{h["level"]}] {h["form"]:40s} «{h["token"]}»  {h["mmss"]}  {h["sentence"]}')
print("----")
print("N2 hits:", sum(1 for h in hits if h["level"]=="N2"))
print("N1 hits:", sum(1 for h in hits if h["level"]=="N1"))
json.dump(hits, open("grammar_hits_raw.json","w",encoding="utf-8"), ensure_ascii=False, indent=1)
